// Offline extraction of authored leg-free garment layers. No pixel processing in-game.
const sharp=require('sharp'),fs=require('node:fs/promises');
(async()=>{
 const source=process.argv[2];if(!source)throw Error('Pass the edited 4-column / 6-row transparent sheet');
 const {data,info}=await sharp(source).ensureAlpha().raw().toBuffer({resolveWithObject:true});
 const kinds=['warrior','hunter','mage','glasscannon','summoner','alchemist'],faces=['down','right','up','left'];
 const cell=112,scale=76/210,layers=[],frames={};
 for(let row=0;row<6;row++)for(let col=0;col<4;col++){
  const cw=info.width/4,ch=info.height/6,raw=Buffer.alloc(cw*ch*4);let x0=cw,y0=ch,x1=0,y1=0;
  for(let y=0;y<ch;y++)for(let x=0;x<cw;x++){
   const s=((row*ch+y)*info.width+col*cw+x)*4,t=(y*cw+x)*4;
   if(data[s+3]<32)continue;data.copy(raw,t,s,s+4);x0=Math.min(x0,x);y0=Math.min(y0,y);x1=Math.max(x1,x);y1=Math.max(y1,y);
  }
  // Discard any disconnected fragment leaking across a source-cell gutter.
  const seen=new Uint8Array(cw*ch),components=[];
  for(let i=0;i<seen.length;i++){if(seen[i]||raw[i*4+3]<32)continue;const q=[i];seen[i]=1;for(let a=0;a<q.length;a++){const n=q[a],px=n%cw,py=Math.floor(n/cw);for(let dy=-1;dy<=1;dy++)for(let dx=-1;dx<=1;dx++){const xx=px+dx,yy=py+dy,j=yy*cw+xx;if(xx<0||xx>=cw||yy<0||yy>=ch||seen[j]||raw[j*4+3]<32)continue;seen[j]=1;q.push(j);}}components.push(q);}
  components.sort((a,b)=>b.length-a.length);for(const c of components.slice(1))for(const i of c)raw[i*4+3]=0;
  x0=cw;y0=ch;x1=0;y1=0;for(const i of components[0]){const x=i%cw,y=Math.floor(i/cw);x0=Math.min(x0,x);x1=Math.max(x1,x);y0=Math.min(y0,y);y1=Math.max(y1,y);}
  // Locate the head rather than the asymmetric weapon/cape bounding box.
  const centres=[];
  for(let y=y0+12;y<y0+78;y++){
   let start=-1,best=[0,0];for(let x=64;x<=208;x++){
    const hit=x<208&&raw[(y*cw+x)*4+3]>60;
    if(hit&&start<0)start=x;if(!hit&&start>=0){if(x-start>best[1]-best[0])best=[start,x];start=-1;}
   }if(best[1]-best[0]>=30)centres.push((best[0]+best[1])/2);
  }
  centres.sort((a,b)=>a-b);const root=centres[Math.floor(centres.length/2)]||128;
  const w=Math.round((x1-x0+1)*scale),h=Math.round((y1-y0+1)*scale);
  const png=await sharp(raw,{raw:{width:cw,height:ch,channels:4}}).extract({left:x0,top:y0,width:x1-x0+1,height:y1-y0+1}).resize(w,h,{kernel:'nearest'}).png().toBuffer();
  const x=col*cell+Math.floor((cell-w)/2),y=row*cell+4;
  layers.push({input:png,left:x,top:y});(frames[kinds[row]]??={})[faces[col]]={x,y,w,h,anchorX:Math.round((root-x0)*scale),anchorY:68};
 }
 await fs.mkdir('assets/locomotion',{recursive:true});
 await sharp({create:{width:cell*4,height:cell*6,channels:4,background:'#00000000'}}).composite(layers).png({palette:true,colours:256,dither:0,compressionLevel:9}).toFile('assets/locomotion/garments.png');
 await fs.writeFile('src/gait-body-frames.js','// Generated by tools/pack-gait-bodies.cjs\nexport const GAIT_BODIES='+JSON.stringify(frames)+';\n');
})();
